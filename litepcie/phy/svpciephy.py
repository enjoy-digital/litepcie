def add_hip_sources(platform, quartus_bindir=None):
    ip_root = _find_quartus_ip_root(quartus_bindir)
    for subdir, files in _HIP_SOURCES.items():
        for f in files:
            path = os.path.join(ip_root, subdir, f)
            if not os.path.exists(path):
                raise OSError(
                    f"Stratix V PCIe hard IP source missing: {path}\n"
                    f"This Quartus installation does not carry the Stratix V PCIe IP sources."
                )
            platform.add_source(path)
    for sdc in _HIP_SDCS:
        platform.add_ip(os.path.join(ip_root, sdc))

# Transceiver Reconfiguration Controller generation ------------------------------------------------

# Number of transceiver reconfiguration interfaces, per Intel's Stratix V PCIe example designs
# (<quartus>/ip/altera/altera_pcie/altera_pcie_hip_ast_ed/example_design/sv/pcie_de_*.qsys):
# gen1/gen2 x8 -> 10, gen3 x8 -> 11, and the bus widths are 70 bits per interface towards the
# transceivers and 46 bits back.
def reconfig_interfaces(nlanes, speed):
    per_lane = {1: 2, 4: 5, 8: 10}[nlanes]
    return per_lane + (1 if speed == "gen3" else 0)

def _build_reconfig_qsys_tcl(name, device, family, ninterfaces):
    parameters = {
        "device_family"                 : family,
        "number_of_reconfig_interfaces" : ninterfaces,
        # Offset cancellation is the reason this block is mandatory on Stratix V.
        "enable_offset"                 : 1,
        "enable_dcd"                    : 0,
        "enable_dcd_power_up"           : 1,
        "enable_analog"                 : 0,
        "enable_eyemon"                 : 0,
        "ber_en"                        : 0,
        "enable_dfe"                    : 0,
        "enable_adce"                   : 0,
        "enable_mif"                    : 0,
        "gui_enable_pll"                : 0,
        "gui_cal_status_port"           : "false",
    }
    tcl = [
        "package require -exact qsys 16.0",
        f"create_system {name}",
        f"set_project_property DEVICE_FAMILY {{{family}}}",
        f"set_project_property DEVICE {{{device}}}",
        "add_instance xr alt_xcvr_reconfig",
    ]
    for k in sorted(parameters):
        tcl.append(f"set_instance_parameter_value xr {k} {{{parameters[k]}}}")
    for iname, itype, idir in [
        ("mgmt_clk_clk",       "clock",  "sink"),
        ("mgmt_rst_reset",     "reset",  "sink"),
        ("reconfig_mgmt",      "avalon", "slave"),
        ("reconfig_to_xcvr",   "conduit", "end"),
        ("reconfig_from_xcvr", "conduit", "end"),
        ("reconfig_busy",      "conduit", "end"),
    ]:
        tcl.append(f"add_interface {iname} {itype} {idir}")
        tcl.append(f"set_interface_property {iname} EXPORT_OF xr.{iname}")
    tcl.append(f"save_system {name}.qsys")
    return "\n".join(tcl) + "\n"

def generate_xcvr_reconfig(name, device, family, ninterfaces, output_dir, quartus_bindir=None,
    force=False):
    """Generate an `alt_xcvr_reconfig` Qsys system and return (qip_path, top_verilog_path).

    Cached on a hash of everything that affects the output, like litedram.phy.intel_uniphy.
    """
    tcl = _build_reconfig_qsys_tcl(name, device, family, ninterfaces)
    _CACHE_VERSION = "1"
    hash = hashlib.sha256((_CACHE_VERSION + tcl).encode()).hexdigest()[:16]

    output_dir = os.path.abspath(output_dir)
    os.makedirs(output_dir, exist_ok=True)
    stampfile  = os.path.join(output_dir, f"{name}.litex_hash")
    qip        = os.path.join(output_dir, name, "synthesis", f"{name}.qip")
    top        = os.path.join(output_dir, name, "synthesis", f"{name}.v")

    if not force and os.path.exists(qip) and os.path.exists(top) and os.path.exists(stampfile):
        if open(stampfile).read().strip() == hash:
            print(f"[SVPCIEPHY] Reusing cached transceiver reconfig IP in {output_dir} (hash {hash}).")
            return qip, top

    qsys_script   = _find_quartus_tool("qsys-script",   quartus_bindir)
    qsys_generate = _find_quartus_tool("qsys-generate", quartus_bindir)

    tclfile = os.path.join(output_dir, f"{name}.tcl")
    with open(tclfile, "w") as f:
        f.write(tcl)

    print(f"[SVPCIEPHY] Generating {name} ({ninterfaces} reconfig interfaces) for {device}.")
    for cmd in [
        [qsys_script,   f"--script={name}.tcl"],
        [qsys_generate, f"{name}.qsys", "--synthesis=VERILOG", f"--family={family}",
                        f"--part={device}"],
    ]:
        r = subprocess.run(cmd, cwd=output_dir)
        if r.returncode != 0:
            raise OSError(
                f"[SVPCIEPHY] {os.path.basename(cmd[0])} failed (exit {r.returncode}).\n"
                f"  cmd: {' '.join(cmd)}\n  cwd: {output_dir}\n"
                f"Rerun it by hand there to see the full Qsys log."
            )
    if not os.path.exists(qip):
        raise OSError(f"[SVPCIEPHY] generation reported success but {qip} is missing.")

    with open(stampfile, "w") as f:
        f.write(hash)
    return qip, top

def probe_reconfig_widths(top_verilog):
    """Read back the generated reconfig top level to learn the reconfig bus widths.

    Read rather than recomputed, so a change in Intel's per-interface bus width cannot silently
    produce a mismatched instantiation.
    """
    src = open(top_verilog).read()
    def width(port):
        m = re.search(r"\[\s*(\d+)\s*:\s*0\s*\]\s+" + port, src)
        if m is None:
            raise ValueError(f"Could not find '{port}' in {top_verilog}.")
        return int(m.group(1)) + 1
    return {
        "to"   : width("reconfig_to_xcvr_reconfig_to_xcvr"),
        "from" : width("reconfig_from_xcvr_reconfig_from_xcvr"),
    }

def _int_params_to_32bit(params):
    """Widen integer Instance parameters to 32 bits.

    LiteX emits an integer parameter as a sized literal of exactly the bits it needs, so
    `vendor_id_hwtcl = 0x1172` comes out as `13'd4466`, and a Verilog parameter takes the *width of
    the override*. Intel's RTL then slices `vendor_id_hwtcl[15:0]` and Quartus errors with
    "index 15 cannot fall outside the declared range [12:0]". Emitting 32-bit literals matches what
    an unsized decimal in hand-written Verilog would give.
    """
    for k, v in params.items():
        if k.startswith("p_") and isinstance(v, int) and not isinstance(v, bool):
            params[k] = Constant(v, 32)
    return params

# Qword alignment ----------------------------------------------------------------------------------

def _tlp_needs_pad(header_dw0, header_dw2, header_dw3):
    """Intel's qword-alignment rule, as a Migen expression.

    The first payload dword must land on a dword lane whose parity matches address bit 2, so one
    padding dword is inserted between header and payload when the packed position has the wrong
    parity:

        3DW header (payload would start at lane 3, odd)  -> pad when addr[2] == 0
        4DW header (payload would start at lane 4, even) -> pad when addr[2] == 1

    For 3DW TLPs address bit 2 is bit 2 of header dword 2. That dword holds address[31:2] for memory
    requests and the Lower Address field for completions, and bit 2 is the right bit either way.
    For 4DW TLPs it is bit 2 of header dword 3 (the low half of the 64-bit address).

    Dataless TLPs (reads, completions without data) carry no payload, so they are never padded.
    """
    fmt_has_data = header_dw0[30]
    fmt_4dw      = header_dw0[29]
    return fmt_has_data & Mux(fmt_4dw, header_dw3[2], ~header_dw2[2])


class _TXQwordAligner(LiteXModule):
    """LitePCIe's packed TLP layout -> Intel's qword-aligned Avalon-ST layout.

    Inserts one padding dword after the header when the alignment rule calls for it, shifting the
    rest of the packet up by one dword lane and emitting an extra beat if the packet no longer fits.
    """
    def __init__(self, data_width):
        assert data_width in [128, 256]
        self.sink   = sink   = stream.Endpoint(phy_layout(data_width))
        self.source = source = stream.Endpoint(phy_layout(data_width))

        # # #

        dws = data_width//32

        def dw(sig, i):
            return sig[32*i:32*(i+1)]

        def be(sig, i):
            return sig[4*i:4*(i+1)]

        # Per-packet state.
        shift      = Signal()   # This packet needs the padding dword.
        in_packet  = Signal()   # Past the first beat of the packet.
        carry_dat  = Signal(32, reset_less=True)
        carry_be   = Signal(4,  reset_less=True)
        flush      = Signal()   # Emitting the spilled dword as an extra beat.
        # Dword index of the first lane of the beat currently on `sink`, saturating past the point
        # where the padding dword can be (it is never further in than dword 4).
        beat_base  = Signal(max=2*dws+1)

        # Padding decision and header size, taken from the header on the first beat and held for the
        # rest of the packet.
        pad_now   = Signal()
        hdr_dws   = Signal(max=5)
        hdr_dws_r = Signal(max=5, reset_less=True)
        self.comb += [
            pad_now.eq(_tlp_needs_pad(dw(sink.dat, 0), dw(sink.dat, 2), dw(sink.dat, 3))),
            hdr_dws.eq(Mux(dw(sink.dat, 0)[29], 4, 3)),
        ]

        active_shift = Signal()
        pad_pos      = Signal(max=5)  # Dword index of the padding dword within the packet.
        self.comb += [
            active_shift.eq(Mux(in_packet, shift,     pad_now)),
            pad_pos.eq(     Mux(in_packet, hdr_dws_r, hdr_dws)),
        ]

        # Datapath. Lane i of this beat is dword `beat_base + i` of the packet; everything at or
        # after the padding position moves up by one dword, everything before it stays put. The
        # padding dword lands in the first beat for a 256-bit datapath, and for a 128-bit one in the
        # first beat for 3-dword headers or the second for 4-dword headers.
        out_dat = Signal(data_width)
        out_be  = Signal(data_width//8)
        for i in range(dws):
            src_dat = dw(sink.dat, i-1) if i > 0 else carry_dat
            src_be  = be(sink.be,  i-1) if i > 0 else carry_be
            lane_dw = Signal(max=3*dws+1)
            self.comb += lane_dw.eq(beat_base + i)
            self.comb += [
                If(~active_shift | (lane_dw < pad_pos),
                    # Straight through: before the insertion point, or nothing to insert.
                    dw(out_dat, i).eq(dw(sink.dat, i)),
                    be(out_be,  i).eq(be(sink.be,  i)),
                ).Elif(lane_dw == pad_pos,
                    dw(out_dat, i).eq(0),
                    be(out_be,  i).eq(0xf),
                ).Else(
                    dw(out_dat, i).eq(src_dat),
                    be(out_be,  i).eq(src_be),
                )
            ]

        # The shifted-out top dword spills into an extra beat when the last input beat is full.
        spill = Signal()
        self.comb += spill.eq(active_shift & sink.last & (be(sink.be, dws-1) != 0))

        self.comb += [
            If(flush,
                source.valid.eq(1),
                source.first.eq(0),
                source.last.eq(1),
                dw(source.dat, 0).eq(carry_dat),
                be(source.be,  0).eq(carry_be),
            ).Else(
                source.valid.eq(sink.valid),
                source.first.eq(sink.first),
                source.last.eq(sink.last & ~spill),
                source.dat.eq(out_dat),
                source.be.eq(out_be),
                sink.ready.eq(source.ready),
            )
        ]

        self.sync += [
            If(flush,
                If(source.ready,
                    flush.eq(0),
                    in_packet.eq(0),
                    beat_base.eq(0),
                )
            ).Elif(sink.valid & sink.ready,
                If(sink.first,
                    shift.eq(pad_now),
                    hdr_dws_r.eq(hdr_dws),
                ),
                carry_dat.eq(dw(sink.dat, dws-1)),
                carry_be.eq(be(sink.be,  dws-1)),
                in_packet.eq(~sink.last),
                If(sink.last,
                    flush.eq(spill),
                    beat_base.eq(0),
                ).Elif(beat_base < 2*dws,
                    # Saturates once it is past any possible padding position (dword 4 at most).
                    beat_base.eq(beat_base + dws),
                )
            )
        ]


class _RXQwordDealigner(LiteXModule):
    """Intel's qword-aligned Avalon-ST layout -> LitePCIe's packed TLP layout.

    The exact inverse of _TXQwordAligner: removes the padding dword the hard IP inserted, pulling
    the rest of the packet down by one dword lane. One beat of latency, because the last lane of an
    output beat comes from the first lane of the next input beat.
    """
    def __init__(self, data_width):
        assert data_width in [128, 256]
        self.sink   = sink   = stream.Endpoint(phy_layout(data_width))
        self.source = source = stream.Endpoint(phy_layout(data_width))

        # # #

        dws = data_width//32

        def dw(sig, i):
            return sig[32*i:32*(i+1)]

        def be(sig, i):
            return sig[4*i:4*(i+1)]

        # Buffered input beat.
        buf_dat   = Signal(data_width,    reset_less=True)
        buf_be    = Signal(data_width//8, reset_less=True)
        buf_first = Signal()
        buf_last  = Signal()
        buf_valid = Signal()

        shift = Signal()

        pad_now = Signal()
        self.comb += pad_now.eq(_tlp_needs_pad(dw(buf_dat, 0), dw(buf_dat, 2), dw(buf_dat, 3)))
        hdr_dws = Signal(max=5)
        self.comb += hdr_dws.eq(Mux(dw(buf_dat, 0)[29], 4, 3))

        active_shift = Signal()
        self.comb += active_shift.eq(Mux(buf_first, pad_now, shift))

        # Emit the buffered beat once the next beat's first dword is available, unless it is the
        # last beat or nothing is being shifted. Byte enables are qword-granular, so a last beat
        # carries at least two dwords and the shift cannot leave a trailing empty beat.
        self.comb += [
            source.valid.eq(buf_valid & (sink.valid | buf_last | ~active_shift)),
            source.first.eq(buf_first),
            source.last.eq(buf_last),
        ]
        for i in range(dws):
            nxt_dat = dw(sink.dat, 0) if i == dws-1 else dw(buf_dat, i+1)
            nxt_be  = be(sink.be,  0) if i == dws-1 else be(buf_be,  i+1)
            if i == dws-1:
                nxt_dat = Mux(buf_last, 0, nxt_dat)
                nxt_be  = Mux(buf_last, 0, nxt_be)
            self.comb += [
                If(~active_shift,
                    dw(source.dat, i).eq(dw(buf_dat, i)),
                    be(source.be,  i).eq(be(buf_be,  i)),
                ).Elif(buf_first & (i < hdr_dws),
                    # Header dwords are not moved.
                    dw(source.dat, i).eq(dw(buf_dat, i)),
                    be(source.be,  i).eq(be(buf_be,  i)),
                ).Else(
                    dw(source.dat, i).eq(nxt_dat),
                    be(source.be,  i).eq(nxt_be),
                )
            ]

        # Input side: accept a beat whenever the buffer is free or is being emitted. When the
        # buffered beat is not the last one, the *next* beat is consumed by the emission of the
        # buffered one only in the sense of being sampled; it is still needed in full, so it is
        # simply loaded into the buffer.
        self.comb += sink.ready.eq(~buf_valid | (source.valid & source.ready))

        self.sync += [
            If(sink.valid & sink.ready,
                buf_dat.eq(sink.dat),
                buf_be.eq(sink.be),
                buf_first.eq(sink.first),
                buf_last.eq(sink.last),
                buf_valid.eq(1),
                If(sink.first,
                    shift.eq(_tlp_needs_pad(dw(sink.dat, 0), dw(sink.dat, 2), dw(sink.dat, 3))),
                ),
            ).Elif(source.valid & source.ready,
                buf_valid.eq(0),
            )
        ]

