"""
Altera/Intel Stratix V PCI Express hard IP (Avalon-ST interface), wrapped for LitePCIe.

Verified on a Microsoft Storey Peak (Azure X930613-001, Stratix V 5SGSMD5): the endpoint enumerates
as 1172:e001 and BAR0 MMIO completes against a Linux host. DMA is not exercised on hardware.
Protocol details cite Intel doc 683093, Stratix V Avalon-ST Interface for PCIe Solutions User Guide.

BAR0 answers 32-bit accesses only, so byte-granular reads abort and return 0xff.

Quartus 25.1std ships no Platform Designer component for this hard IP, so the parameterised top
level `altpcie_sv_hip_ast_hwtcl` is instantiated directly and its sources registered from the
Quartus installation. No pre-generated IP directory is needed. The Transceiver Reconfiguration
Controller (`alt_xcvr_reconfig`) is generated by qsys-generate at build time and cached.

Qword alignment: payload is not packed immediately after the header. The first payload dword sits at
a dword lane whose parity matches address bit 2 of the TLP (doc 683093 s5.2.1, Figure 31). On the
256-bit interface:

    3DW header, address bit2 = 0 : H0 H1 H2 PAD D0 D1 D2 D3   one padding dword
    3DW header, address bit2 = 1 : H0 H1 H2 D0  D1 D2 D3 D4   packed
    4DW header, address bit2 = 0 : H0 H1 H2 H3  D0 D1 D2 D3   packed
    4DW header, address bit2 = 1 : H0 H1 H2 H3  PAD D0 D1 D2  one padding dword

The deciding bit is bit 2 of header dword 2 for 3DW headers and dword 3 for 4DW. Dataless TLPs are
never padded. LitePCIe uses the packed layout only, so `_TXQwordAligner` and `_RXQwordDealigner`
convert at the PHY boundary. `c5pciephy` omits this and the same rule applies to Cyclone V (683666).

Not implemented: Gen3, more than one endpoint (the second hard IP block is disabled in the device,
see https://github.com/ruurdk/sv_second_pcie_hip), `rx_st_be` (byte enables come from `rx_st_empty`
and are qword-granular), `rx_st_mask`, TX parity, hard-IP reconfiguration, CvP, MSI-X and AER.
"""

