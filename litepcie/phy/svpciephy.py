            i_pme_to_cr                   = 0,
            i_pm_event                    = 0,

            # MSI.
            i_app_msi_req                 = cfg_msi.valid,
            o_app_msi_ack                 = cfg_msi.ready,
            i_app_msi_num                 = 0,
            i_app_msi_tc                  = 0,
            i_aer_msi_num                 = 0,
            i_pex_msi_num                 = 0,
