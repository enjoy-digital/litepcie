# Quartus / Qsys discovery -------------------------------------------------------------------------

def _find_quartus_tool(name, quartus_bindir=None):
    """Locate a Quartus or Qsys binary.

    The Qsys tools live in <quartus>/sopc_builder/bin, which is deliberately *not* on PATH in a
    normal Quartus setup (only <quartus>/quartus/bin is), so searching PATH alone is not enough.
    """
    if quartus_bindir is not None:
        for cand in [
            os.path.join(quartus_bindir, name),
            os.path.join(quartus_bindir, "..", "sopc_builder", "bin", name),
        ]:
            cand = os.path.normpath(cand)
            if os.path.exists(cand):
                return cand
    found = shutil.which(name)
    if found is not None:
        return found

    anchor = shutil.which("quartus_sh") or shutil.which("quartus_map")
    if anchor is not None:
        qbin = os.path.dirname(os.path.realpath(anchor))
        cand = os.path.normpath(os.path.join(qbin, "..", "sopc_builder", "bin", name))
        if os.path.exists(cand):
            return cand

    raise OSError(
        f"Could not find {name}. Qsys tools ship in <quartus>/sopc_builder/bin, which is usually "
        f"not on PATH. Add that directory to PATH, or pass quartus_bindir= to SVPCIEPHY."
    )

def _find_quartus_ip_root(quartus_bindir=None):
    """Return <quartus install>/ip/altera, where the PCIe hard IP sources live."""
    anchor = None
    if quartus_bindir is not None:
        for name in ["quartus_sh", "quartus_map"]:
            cand = os.path.join(quartus_bindir, name)
            if os.path.exists(cand):
                anchor = cand
                break
    if anchor is None:
        anchor = shutil.which("quartus_sh") or shutil.which("quartus_map")
    if anchor is None:
        raise OSError("Could not find Quartus (quartus_sh not on PATH); needed to locate the "
                      "Stratix V PCIe hard IP sources.")
    qbin = os.path.dirname(os.path.realpath(anchor))            # <root>/quartus/bin
    ip   = os.path.normpath(os.path.join(qbin, "..", "..", "ip", "altera"))
    if not os.path.isdir(ip):
        raise OSError(f"Quartus IP directory not found at {ip}.")
    return ip

